<?php
// Handles the WordPress admin settings and submissions pages.

if ( ! defined( 'ABSPATH' ) ) {
    exit;
}

class SDF_Admin {

    /**
     * Initialize admin hooks.
     */
    public static function init() {

        add_action( 'admin_menu', array( 'SDF_Admin', 'add_admin_menu' ) );

        add_action( 'admin_init', array( 'SDF_Admin', 'register_settings' ) );

        add_action(
            'admin_enqueue_scripts',
            array( 'SDF_Admin', 'enqueue_admin_scripts' )
        );
    }

    /**
     * Register admin menu pages.
     */
    public static function add_admin_menu() {

        add_menu_page(
            'Simple Dynamic Form',
            'Simple Dynamic Form',
            'manage_options',
            'sdf-settings',
            array( 'SDF_Admin', 'render_settings_page' ),
            'dashicons-feedback',
            25
        );

        add_submenu_page(
            'sdf-settings',
            'Form Submissions',
            'Submissions',
            'manage_options',
            'sdf-submissions',
            array( 'SDF_Admin', 'render_submissions_page' )
        );
    }

    /**
     * Register plugin settings.
     */
    public static function register_settings() {

        register_setting(
            'sdf_settings_group',
            'sdf_settings',
            array(
                'sanitize_callback' => array( 'SDF_Admin', 'sanitize_settings' )
            )
        );
    }

    /**
     * Sanitize settings before saving.
     */
    public static function sanitize_settings( $input ) {

        $fields = SDF_Fields::get_fields();

        $sanitized_settings = array();

        foreach ( $fields as $field_key => $field ) {

            // Check whether the field should be visible.
            $show = ! empty( $input[ $field_key ]['show'] ) ? 1 : 0;

            // Check whether the field should be required.
            $required = ! empty( $input[ $field_key ]['required'] ) ? 1 : 0;

            // A hidden field cannot be required.
            if ( ! $show ) {
                $required = 0;
            }

            $sanitized_settings[ $field_key ] = array(
                'show'     => $show,
                'required' => $required
            );
        }

        // Ensure at least one field remains visible.
        $has_visible_field = false;

        foreach ( $sanitized_settings as $field_setting ) {

            if ( $field_setting['show'] ) {
                $has_visible_field = true;
                break;
            }
        }

        if ( ! $has_visible_field ) {

            add_settings_error(
                'sdf_settings',
                'sdf_no_visible_fields',
                'At least one form field must be visible.',
                'error'
            );

            return get_option(
                'sdf_settings',
                SDF_Fields::get_default_settings()
            );
        }

        return $sanitized_settings;
    }

    /**
     * Load the React admin application.
     */
   public static function enqueue_admin_scripts( $hook ) {

    // Load React only on the plugin settings page.
    if ( 'toplevel_page_sdf-settings' !== $hook ) {
        return;
    }

    // Path to the generated asset metadata file.
    $asset_file = SDF_PLUGIN_DIR . 'admin-app/build/index.asset.php';

    // Make sure the React build exists.
    if ( ! file_exists( $asset_file ) ) {
        return;
    }

    // Load dependencies and version generated by wp-scripts.
    $asset = require $asset_file;

    // Path to the compiled React JavaScript file.
    $script_path = SDF_PLUGIN_DIR . 'admin-app/build/index.js';

    // Make sure the compiled JavaScript file exists.
    if ( ! file_exists( $script_path ) ) {
        return;
    }

    // Load the compiled React application.
    wp_enqueue_script(
        'sdf-admin-app',
        SDF_PLUGIN_URL . 'admin-app/build/index.js',
        $asset['dependencies'],
        $asset['version'],
        true
    );

    // Prepare WordPress REST API information for React.
    $settings = array(
        'root'  => esc_url_raw( rest_url() ),
        'nonce' => wp_create_nonce( 'wp_rest' ),
    );

    // Define the settings before the React JavaScript executes.
    wp_add_inline_script(
        'sdf-admin-app',
        'window.sdfSettings = ' . wp_json_encode( $settings ) . ';',
        'before'
    );
}

    /**
     * Render the React settings page.
     */
    public static function render_settings_page() {

        if ( ! current_user_can( 'manage_options' ) ) {
            return;
        }
        ?>

        <div class="wrap">

            <h1>Simple Dynamic Form Settings</h1>

            <p>
                Manage the fields displayed in your dynamic form.
            </p>

            <!-- React will render the settings interface inside this element. -->
            <div id="sdf-react-root"></div>

            <hr>

            <h3>Form Shortcode</h3>

            <p>
                Use the following shortcode on any WordPress page
                to display your dynamic form:
            </p>

            <code>[sdf_form]</code>

        </div>

        <?php
    }

    /**
     * Render submissions page.
     */
    public static function render_submissions_page() {

        if ( ! current_user_can( 'manage_options' ) ) {
            return;
        }

        global $wpdb;

        $table_name = $wpdb->prefix . 'sdf_submissions';

        $per_page = 10;

        $current_page = isset( $_GET['paged'] )
            ? max( 1, absint( $_GET['paged'] ) )
            : 1;

        $offset = ( $current_page - 1 ) * $per_page;

        $total_items = (int) $wpdb->get_var(
            "SELECT COUNT(*) FROM {$table_name}"
        );

        $total_pages = (int) ceil( $total_items / $per_page );

        $submissions = $wpdb->get_results(
            $wpdb->prepare(
                "SELECT * FROM {$table_name} ORDER BY created_at DESC LIMIT %d OFFSET %d",
                $per_page,
                $offset
            )
        );
        ?>

        <div class="wrap">

            <h1>Form Submissions</h1>

            <table class="widefat striped">

                <thead>
                    <tr>
                        <th>ID</th>
                        <th>Full Name</th>
                        <th>Email</th>
                        <th>Phone</th>
                        <th>Age</th>
                        <th>Website</th>
                        <th>City</th>
                        <th>Message</th>
                        <th>Submitted At</th>
                    </tr>
                </thead>

                <tbody>

                    <?php if ( ! empty( $submissions ) ) : ?>

                        <?php foreach ( $submissions as $submission ) : ?>

                            <tr>

                                <td><?php echo esc_html( $submission->id ); ?></td>

                                <td><?php echo esc_html( $submission->full_name ); ?></td>

                                <td><?php echo esc_html( $submission->email ); ?></td>

                                <td><?php echo esc_html( $submission->phone ); ?></td>

                                <td><?php echo esc_html( $submission->age ); ?></td>

                                <td>
                                    <?php if ( ! empty( $submission->website ) ) : ?>
                                        <a
                                            href="<?php echo esc_url( $submission->website ); ?>"
                                            target="_blank"
                                            rel="noopener noreferrer"
                                        >
                                            <?php echo esc_html( $submission->website ); ?>
                                        </a>
                                    <?php endif; ?>
                                </td>

                                <td><?php echo esc_html( $submission->city ); ?></td>

                                <td><?php echo esc_html( $submission->message ); ?></td>

                                <td><?php echo esc_html( $submission->created_at ); ?></td>

                            </tr>

                        <?php endforeach; ?>

                    <?php else : ?>

                        <tr>
                            <td colspan="9">
                                No submissions found.
                            </td>
                        </tr>

                    <?php endif; ?>

                </tbody>

            </table>

            <?php if ( $total_pages > 1 ) : ?>

                <div class="tablenav">
                    <div class="tablenav-pages">

                        <?php

                        echo wp_kses_post(
                            paginate_links(
                                array(
                                    'base' => add_query_arg(
                                        'paged',
                                        '%#%',
                                        menu_page_url( 'sdf-submissions', false )
                                    ),
                                    'format'    => '',
                                    'current'   => $current_page,
                                    'total'     => $total_pages,
                                    'prev_text' => '&laquo;',
                                    'next_text' => '&raquo;'
                                )
                            )
                        );

                        ?>

                    </div>
                </div>

            <?php endif; ?>

        </div>

        <?php
    }
}
